// Private Helper functions
pub fn match_closing_char(opening: char) -> char {
    match opening {
        '(' => ')',
        '<' => '>',
        '{' => '}',
        '[' => ']',
        '\u{2018}' => '\u{2019}', // ' '
        '\u{201C}' => '\u{201D}', // " "
        '\u{201E}' => '\u{201C}', // „ "
        '\u{201F}' => '\u{201E}', // ‟ „
        '\u{201A}' => '\u{2018}', // ‚ '
        '\u{201B}' => '\u{201A}', // ‛ ‚
        '\u{2039}' => '\u{203A}', // ‹ ›
        '\u{00AB}' => '\u{00BB}', // « »
        '\u{275B}' => '\u{275C}', // ❛ ❜
        '\u{275D}' => '\u{275E}', // ❝ ❞
        '\u{2E42}' => '\u{201D}', // ⹂ "
        '\u{300C}' => '\u{300D}', // 「 」
        '\u{300E}' => '\u{300F}', // 『 』
        '\u{FE41}' => '\u{FE42}', // ﹁ ﹂
        '\u{FE43}' => '\u{FE44}', // ﹃ ﹄
        '\u{FF62}' => '\u{FF63}', // ｢ ｣ halfwidth corner brackets
        _ => opening,
    }
}
